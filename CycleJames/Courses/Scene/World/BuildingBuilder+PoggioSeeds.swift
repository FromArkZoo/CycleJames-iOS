    /// The seed of a Riviera house's plan: the one it was first built with
    /// (`rivieraSeedsByCourse`, centre within 1.5 m), else `rivieraKey`.
    static func rivieraSeed(_ b: SceneryFile.Building, courseID: String?) -> Int {
        let c = footprintCentre(b)
        if let rows = courseID.flatMap({ rivieraSeedsByCourse[$0] }) {
            for i in stride(from: 0, to: rows.count - 2, by: 3)
            where simd_distance(SIMD2(rows[i], rows[i + 1]), c) < 1.5 {
                return Int(rows[i + 2])
            }
        }
        return rivieraKey(b)
    }
